/* Mission 11A (Agent #2) — built-in material preset library. UI + material
   editing only. Every preset is a plain parameter object: no THREE import here,
   so this module is data and stays importable from anywhere (including tests).

   Values are authored for the studio's existing PBR setup: a MeshStandard/
   MeshPhysical material lit by the three-light rig plus the RoomEnvironment
   probe, so `env` (envMapIntensity) is what makes chrome read as chrome.
   `need` names the one capability a preset requires of the material — "clear"
   (clearcoat) or "trans" (transmission) — and MaterialsManager upgrades the
   material class only when a preset actually asks for it, and only back down on
   reset. `tex` names a procedurally generated, module-cached texture, so a
   preset never duplicates a texture across meshes. */

